  var MONTHS_GEN = ["января", "февраля", "марта", "апреля", "мая", "июня",
    "июля", "августа", "сентября", "октября", "ноября", "декабря"];

  function pad(n) { return n < 10 ? "0" + n : String(n); }

  /** Локальная дата в виде YYYY-MM-DD — сравнение строк безопаснее арифметики с TZ. */
  function ymd(d) {
    return d.getFullYear() + "-" + pad(d.getMonth() + 1) + "-" + pad(d.getDate());
  }

  function parse(iso) {
    var p = iso.split("-");
    return new Date(Number(p[0]), Number(p[1]) - 1, Number(p[2]));
  }

  function human(iso) {
    var d = parse(iso);
    return d.getDate() + " " + MONTHS_GEN[d.getMonth()] + " " + d.getFullYear();
  }

  function humanDate(d) {
    return d.getDate() + " " + MONTHS_GEN[d.getMonth()] + " " + d.getFullYear();
  }

  function daysBetween(fromIso, toIso) {
    return Math.round((parse(toIso) - parse(fromIso)) / 86400000);
  }

  /** «19 дней» / «1 день» / «22 дня» — без этого виджет звучит как робот. */
  function plural(n, one, few, many) {
    var mod10 = n % 10, mod100 = n % 100;
    if (mod10 === 1 && mod100 !== 11) return n + " " + one;
    if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return n + " " + few;
    return n + " " + many;
  }

