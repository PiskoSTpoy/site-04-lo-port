// Дата актуальности ставок для оговорки под калькулятором.
//
// Берётся не «сегодня» и не дата сборки: ставка актуальна не потому, что сайт
// пересобрали, а потому, что её последний раз пересматривали. Единственное место,
// где цифры 4 000 / 6 000 ₽ реально живут, — src/js/calculator.js (объект rates),
// поэтому дата актуальности = mtime именно этого файла. Тронули ставку — дата
// сдвинулась сама; пересобрали сайт без правки ставок — дата осталась прежней.
//
// season.checked сюда не подходит: это дата проверки ДОРОЖНОГО ПРИКАЗА, к прайсу
// отношения не имеющая, и выдавать её за дату проверки цен было бы неправдой.
const fs = require("node:fs");
const path = require("node:path");

const RATE_FILE = path.join(__dirname, "..", "js", "calculator.js");

const MONTHS = ["января", "февраля", "марта", "апреля", "мая", "июня",
  "июля", "августа", "сентября", "октября", "ноября", "декабря"];

module.exports = () => {
  const d = fs.statSync(RATE_FILE).mtime;
  const pad = (n) => String(n).padStart(2, "0");
  return {
    updatedIso: `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`,
    updatedHuman: `${d.getDate()} ${MONTHS[d.getMonth()]} ${d.getFullYear()}`,
  };
};
